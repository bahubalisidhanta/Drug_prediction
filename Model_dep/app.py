import pickle
import pandas as pd
from textblob import TextBlob
import spacy
import numpy as np
import streamlit as st

enc = pickle.load(open('encoder_lb.pkl','rb'))
model = pickle.load(open('model_gbc.pkl', 'rb'))

def sentiment_count(text):
    sent = TextBlob(text)
    sent_count = sent.sentiment.polarity
    return sent_count


nlp = spacy.load('en_core_web_sm')

def spacy_preprocess(text):
    if pd.isnull(text):
        return ""

    doc = nlp(text.lower())

    tokens = []
    for token in doc:

        if not token.is_stop and not token.is_punct and not token.like_num and not token.is_space and not token.is_bracket and not token.pos_ in ['SYM']:   # Removing Stopwords, Punctuations, Numbers, White spaces, Brackets, Symbols
            tokens.append(token.lemma_)

    return " ".join(tokens)

st.title("Patient condition prediction")
rating = st.number_input("Enter the rating",min_value=0,max_value=10)
review = st.text_input("Enter review")

if st.button("Predict"):
    review = spacy_preprocess(review)
    review = sentiment_count(review)
    a = model.predict(pd.DataFrame([[rating, review]], columns=['rating', 'cleaned_review']))[0]
    st.subheader("Predicted condition")
    st.write(enc.inverse_transform([a])[0])